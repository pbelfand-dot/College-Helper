/**
 * Deterministic ids so tests and e2e specs can rely on them.
 * The index is zero-padded so `r1` and `r10` cannot collapse to the same id.
 */
function demoId(prefix: string, index: number): string {
  const suffix = `${prefix}${String(index).padStart(3, '0')}`.padEnd(12, '0').slice(0, 12);
  return `00000000-0000-4000-8000-${suffix.replace(/[^0-9a-f]/g, (c) =>
    (c.charCodeAt(0) % 10).toString(),
  )}`;
}

