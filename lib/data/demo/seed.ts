/** 11:59pm on a day `days` from now, as an ISO string. */
function deadlineIn(days: number, now: Date): string {
  return setMinutes(setHours(startOfDay(addDays(now, days)), 23), 59).toISOString();
}

function dayIn(days: number, now: Date): string {
  return startOfDay(addDays(now, days)).toISOString();
}

